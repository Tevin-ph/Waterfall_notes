// Reads a few Lucide icons (ISC license) and writes them as { name: "<inner svg markup>" } for the app to inline.
import { readFileSync, writeFileSync } from "node:fs";
const names = ["play", "pause", "rotate-ccw", "save", "download", "keyboard", "circle", "music", "timer", "repeat", "type", "library", "plus", "scan", "piano", "sliders-horizontal"];
const out = {};
for (const n of names) {
  let svg;
  try { svg = readFileSync(new URL(`./node_modules/lucide-static/icons/${n}.svg`, import.meta.url), "utf8"); } catch { continue; }
  out[n] = svg.replace(/<!--[\s\S]*?-->/g, "").replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
}
writeFileSync(new URL("../falling-note-proto/vendor/icons.js", import.meta.url),
  "// Lucide icons (ISC). Generated by build-bp/make-icons.mjs.\nexport const ICONS = " + JSON.stringify(out) + ";\n");
console.log("icons:", Object.keys(out).join(", "));
